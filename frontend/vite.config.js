import { defineConfig } from "vite";
import react from "@vitejs/plugin-react";
import fs from "node:fs";
import path from "node:path";
import { apiOriginFrom, buildCsp, CSP_REPORT_ONLY_HEADER } from "./csp.config.js";

// Check if we are building for the desktop app
const isElectron = process.env.ELECTRON === "true";

// Build-only: delivers the CSP from csp.config.js (see the comment there).
// The dev server gets no CSP; Vite HMR needs inline scripts and ws:.
function cspPlugin() {
  let config;
  return {
    name: "orka-csp",
    apply: "build",
    configResolved(resolved) {
      config = resolved;
    },
    transformIndexHtml() {
      if (!isElectron) return [];
      const content = buildCsp({ apiOrigin: apiOriginFrom(config.env.VITE_API_URL), meta: true });
      return [{ tag: "meta", attrs: { "http-equiv": "Content-Security-Policy", content }, injectTo: "head-prepend" }];
    },
    closeBundle() {
      if (isElectron) return;
      const policy = buildCsp({ apiOrigin: apiOriginFrom(config.env.VITE_API_URL) });
      const outDir = path.resolve(config.root, "dist-csp");
      fs.mkdirSync(outDir, { recursive: true });
      fs.writeFileSync(
        path.join(outDir, "nginx-csp.conf"),
        `# Generated by vite build from csp.config.js. Do not edit.\nadd_header ${CSP_REPORT_ONLY_HEADER} "${policy}" always;\n`,
      );

      // firebase.json / vercel.json hold a static copy of the generic policy.
      const expected = buildCsp({ apiOrigin: null });
      for (const file of ["firebase.json", "vercel.json"]) {
        try {
          const raw = fs.readFileSync(path.resolve(config.root, file), "utf8");
          if (!raw.includes(`"${expected}"`)) {
            config.logger.warn(`[orka-csp] ${file} CSP differs from csp.config.js buildCsp({ apiOrigin: null }). Update it to:\n${expected}`);
          }
        } catch {
          // file absent: nothing to check
        }
      }
    },
  };
}

export default defineConfig({
  plugins: [react(), cspPlugin()],
  // Use relative paths for Electron, absolute for Web
  base: isElectron ? './' : '/', 
  server: {
    port: 3000,
    proxy: {
      "/api": {
        target: "http://localhost:5001",
        changeOrigin: true,
        secure: false,
      },
    },
  },
});